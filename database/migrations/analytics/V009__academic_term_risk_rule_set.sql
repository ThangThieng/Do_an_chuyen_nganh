CREATE TABLE analytics.academic_term (
    academic_year  analytics.academic_year_t  NOT NULL,
    semester       analytics.semester_t       NOT NULL,
    start_date     DATE                       NOT NULL,
    end_date       DATE                       NOT NULL,
    week1_start    DATE                       NOT NULL,
    note           TEXT,
    CONSTRAINT pk_academic_term PRIMARY KEY (academic_year, semester),
    CONSTRAINT ck_academic_term_dates CHECK (end_date > start_date AND week1_start <= start_date + 6)
);
COMMENT ON TABLE analytics.academic_term IS 'Lịch học kỳ; week1_start = ngày bắt đầu tuần học 1 (đánh số tuần trên đồ thị xu hướng)';

