-- -----------------------------------------------------------------------------
-- risk_rule_set: bộ luật chấm điểm/xếp mức rủi ro. Mỗi lần lưu là một dòng mới (không sửa phiên bản cũ).
--   scope = GLOBAL : luật mặc định của trường (course_id NULL), ETL tự phát hành phiên bản khi etl/config.py đổi
--   scope = COURSE : luật riêng của một môn do giảng viên đặt trên màn hình "Thiết lập cảnh báo"
-- params = {thresholds{...}, weights{attendance, inactivity, assignment}, level_rules{...}, extra_rules[...]}
-- -----------------------------------------------------------------------------
CREATE TABLE analytics.risk_rule_set (
    rule_set_id    INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope          VARCHAR(6)    NOT NULL,
    course_id      INTEGER,
    version_no     INTEGER       NOT NULL,
    label          VARCHAR(40)   NOT NULL,
    preset         VARCHAR(10)   NOT NULL DEFAULT 'CUSTOM',
    params         JSONB         NOT NULL,
    note           TEXT,
    created_by     INTEGER,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    superseded_at  TIMESTAMPTZ,
    CONSTRAINT fk_rule_created_by  FOREIGN KEY (created_by) REFERENCES analytics.app_user (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_rule_scope       CHECK (scope IN ('GLOBAL', 'COURSE')),
    CONSTRAINT ck_rule_scope_course CHECK ((scope = 'GLOBAL') = (course_id IS NULL)),
    CONSTRAINT ck_rule_preset      CHECK (preset IN ('DEFAULT', 'THEORY', 'PRACTICE', 'PROJECT', 'CUSTOM')),
    CONSTRAINT ck_rule_version     CHECK (version_no >= 1),
    CONSTRAINT ck_rule_params      CHECK (jsonb_typeof(params) = 'object'
                                          AND params ? 'thresholds' AND params ? 'weights'
                                          AND params ? 'level_rules' AND params ? 'extra_rules'),
    CONSTRAINT ck_rule_active      CHECK (is_active = (superseded_at IS NULL))
);
COMMENT ON TABLE analytics.risk_rule_set IS 'Bộ luật cảnh báo có phiên bản: GLOBAL (mặc định của trường) hoặc COURSE (luật riêng của môn)';
COMMENT ON COLUMN analytics.risk_rule_set.params IS
    '{"thresholds":{absence_yellow,absence_red,inactive_yellow_days,inactive_red_days,low_access_ratio,missing_yellow,missing_red},'
    '"weights":{attendance,inactivity,assignment},"level_rules":{red_if_inactivity_red,red_min_red_criteria,red_min_total},'
    '"extra_rules":[{"type":"consecutive_missing|absent_sessions|absence_rate|inactive_days|missing_count",...,"level":"RED|YELLOW"}]}';

CREATE UNIQUE INDEX ux_rule_version ON analytics.risk_rule_set (scope, COALESCE(course_id, 0), version_no);
-- Mỗi môn tối đa 1 bộ luật riêng đang hoạt động; toàn trường đúng 1 bộ GLOBAL đang hoạt động
CREATE UNIQUE INDEX ux_rule_active_course ON analytics.risk_rule_set (course_id) WHERE is_active AND scope = 'COURSE';
CREATE UNIQUE INDEX ux_rule_active_global ON analytics.risk_rule_set ((scope)) WHERE is_active AND scope = 'GLOBAL';

