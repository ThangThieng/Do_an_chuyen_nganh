-- -----------------------------------------------------------------------------
-- message_template: mẫu hệ thống (owner_id NULL, chỉ đọc) + mẫu riêng của giảng viên
-- -----------------------------------------------------------------------------
CREATE TABLE analytics.message_template (
    template_id  INTEGER       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     INTEGER,
    code         VARCHAR(40)   NOT NULL,
    name         VARCHAR(120)  NOT NULL,
    purpose      VARCHAR(20)   NOT NULL DEFAULT 'GENERAL',
    subject      VARCHAR(200)  NOT NULL,
    body         TEXT          NOT NULL,
    is_active    BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_template_owner  FOREIGN KEY (owner_id) REFERENCES analytics.app_user (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_template_purpose CHECK (purpose IN ('RISK_HIGH', 'INACTIVE', 'MISSING_WORK', 'CHECK_IN', 'GENERAL')),
    CONSTRAINT ck_template_text   CHECK (length(btrim(subject)) > 0 AND length(btrim(body)) > 0 AND length(body) <= 5000)
);
CREATE UNIQUE INDEX ux_template_owner_code ON analytics.message_template (COALESCE(owner_id, 0), code);
CREATE TRIGGER trg_template_updated_at
    BEFORE UPDATE ON analytics.message_template
    FOR EACH ROW EXECUTE FUNCTION analytics.set_updated_at();
COMMENT ON TABLE analytics.message_template IS 'Mẫu tin nhắn can thiệp; biến {ten_sv}, {tinh_hinh}... được điền từ snapshot rủi ro mới nhất';

