-- -----------------------------------------------------------------------------
-- auto_prompt_rule: quy tắc nhắc tự động của một môn
-- -----------------------------------------------------------------------------
CREATE TABLE analytics.auto_prompt_rule (
    rule_id           INTEGER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    course_id         INTEGER       NOT NULL,
    created_by        INTEGER       NOT NULL,
    name              VARCHAR(120)  NOT NULL,
    trigger_type      VARCHAR(20)   NOT NULL,
    params            JSONB         NOT NULL DEFAULT '{}',
    channels          TEXT[]        NOT NULL,
    template_id       INTEGER       NOT NULL,
    send_mode         VARCHAR(6)    NOT NULL DEFAULT 'REVIEW',
    cooldown_days     SMALLINT      NOT NULL DEFAULT 7,
    is_active         BOOLEAN       NOT NULL DEFAULT TRUE,
    last_run_at       TIMESTAMPTZ,
    last_run_summary  JSONB,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_prompt_creator  FOREIGN KEY (created_by) REFERENCES analytics.app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_prompt_template FOREIGN KEY (template_id) REFERENCES analytics.message_template (template_id) ON DELETE RESTRICT,
    CONSTRAINT ck_prompt_trigger  CHECK (trigger_type IN ('INACTIVE_DAYS', 'BECAME_RED', 'MISSED_DEADLINE')),
    CONSTRAINT ck_prompt_channels CHECK (cardinality(channels) >= 1 AND channels <@ ARRAY['MOODLE', 'EMAIL']::text[]),
    CONSTRAINT ck_prompt_mode     CHECK (send_mode IN ('AUTO', 'REVIEW')),
    CONSTRAINT ck_prompt_cooldown CHECK (cooldown_days BETWEEN 1 AND 60),
    CONSTRAINT ck_prompt_params   CHECK (jsonb_typeof(params) = 'object')
);
CREATE INDEX ix_prompt_course ON analytics.auto_prompt_rule (course_id) WHERE is_active;
CREATE TRIGGER trg_prompt_updated_at
    BEFORE UPDATE ON analytics.auto_prompt_rule
    FOR EACH ROW EXECUTE FUNCTION analytics.set_updated_at();
COMMENT ON TABLE analytics.auto_prompt_rule IS 'Quy tắc nhắc tự động: INACTIVE_DAYS {days}, BECAME_RED {}, MISSED_DEADLINE {days_after}';

-- -----------------------------------------------------------------------------
-- outbound_message: hàng đợi gửi + nhật ký + bằng chứng (mã xác nhận do máy chủ nhận trả về)
-- -----------------------------------------------------------------------------
CREATE TABLE analytics.outbound_message (
    message_id          BIGINT        GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    course_id           INTEGER       NOT NULL,
    user_id             INTEGER       NOT NULL,
    sender_id           INTEGER       NOT NULL,
    origin              VARCHAR(6)    NOT NULL,
    rule_id             INTEGER,
    template_id         INTEGER,
    channel             VARCHAR(6)    NOT NULL,
    recipient           VARCHAR(255)  NOT NULL,
    recipient_name      VARCHAR(255),
    subject             VARCHAR(255),
    body                TEXT          NOT NULL,
    status              VARCHAR(14)   NOT NULL,
    attempts            SMALLINT      NOT NULL DEFAULT 0,
    next_attempt_at     TIMESTAMPTZ,
    last_error          TEXT,
    delivery_mode       VARCHAR(10),
    delivered_to        VARCHAR(255),
    provider_ref        VARCHAR(255),
    provider_meta       JSONB,
    idempotency_key     VARCHAR(160)  NOT NULL,
    risk_level_at_time  analytics.risk_level_t,
    snapshot_date       DATE,
    intervention_id     BIGINT,
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    sent_at             TIMESTAMPTZ,
    CONSTRAINT fk_outbound_sender    FOREIGN KEY (sender_id) REFERENCES analytics.app_user (user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_outbound_rule      FOREIGN KEY (rule_id) REFERENCES analytics.auto_prompt_rule (rule_id) ON DELETE SET NULL,
    CONSTRAINT fk_outbound_template  FOREIGN KEY (template_id) REFERENCES analytics.message_template (template_id) ON DELETE SET NULL,
    CONSTRAINT fk_outbound_intervention FOREIGN KEY (intervention_id) REFERENCES analytics.intervention_log (id) ON DELETE SET NULL,
    CONSTRAINT uq_outbound_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_outbound_origin    CHECK (origin IN ('MANUAL', 'AUTO')),
    CONSTRAINT ck_outbound_channel   CHECK (channel IN ('MOODLE', 'EMAIL')),
    CONSTRAINT ck_outbound_status    CHECK (status IN ('PENDING_REVIEW', 'QUEUED', 'SENDING', 'SENT', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_outbound_sent      CHECK ((status = 'SENT') = (sent_at IS NOT NULL)),
    CONSTRAINT ck_outbound_sent_ref  CHECK (status <> 'SENT' OR provider_ref IS NOT NULL),
    CONSTRAINT ck_outbound_mode      CHECK (delivery_mode IS NULL OR delivery_mode IN ('FILE', 'REDIRECT', 'LIVE', 'STUB')),
    CONSTRAINT ck_outbound_attempts  CHECK (attempts BETWEEN 0 AND 20),
    CONSTRAINT ck_outbound_manual    CHECK (origin = 'AUTO' OR rule_id IS NULL)
);
CREATE INDEX ix_outbound_course_time ON analytics.outbound_message (course_id, created_at DESC);
CREATE INDEX ix_outbound_user ON analytics.outbound_message (course_id, user_id, created_at DESC);
CREATE INDEX ix_outbound_queue ON analytics.outbound_message (next_attempt_at) WHERE status = 'QUEUED';
CREATE INDEX ix_outbound_rule ON analytics.outbound_message (rule_id, user_id, created_at DESC) WHERE rule_id IS NOT NULL;
CREATE TRIGGER trg_outbound_updated_at
    BEFORE UPDATE ON analytics.outbound_message
    FOR EACH ROW EXECUTE FUNCTION analytics.set_updated_at();
COMMENT ON TABLE analytics.outbound_message IS 'Tin gửi tới sinh viên (Moodle/email): hàng đợi, thử lại, nhật ký và mã xác nhận (provider_ref)';
COMMENT ON COLUMN analytics.outbound_message.provider_ref IS 'Moodle: msgid (mdl_messages.id); Email: Message-ID';
COMMENT ON COLUMN analytics.outbound_message.delivery_mode IS 'FILE = ghi .eml; REDIRECT = SMTP thật, chuyển tới hộp thư kiểm thử; LIVE = tới người nhận thật; STUB = Moodle mô phỏng';

